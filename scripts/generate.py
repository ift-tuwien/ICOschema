"""Regenerate the Python and Rust code from the LinkML schema.

    uv run python scripts/generate.py            # write icoschema/schema/generated/{python,rust}
    uv run python scripts/generate.py --check    # fail if the committed files are stale

The Rust crate is what `gen-rust` writes, minus the parts this repository does not use (the
PyO3 stubs and the `stub_gen` binary), with a fixed `lib.rs` (the generated shim re-exports
`chrono` without depending on it) and a trimmed `Cargo.toml`. Both are reproducible: the same
schema always gives byte-identical Rust files.
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "icoschema/schema/linkml/dataset.yaml"
PYTHON_OUT = ROOT / "icoschema/schema/generated/python/dataset.py"
RUST_OUT = ROOT / "icoschema/schema/generated/rust"
RUST_FILES = ("mod.rs", "poly.rs", "poly_containers.rs", "serde_utils.rs")

LIB_RS = """\
//! Generated from `icoschema/schema/linkml/dataset.yaml`: run `just generate`, do not edit.
//!
//! Plain data types (no behaviour); the convenience API lives in the `icoschema` crate.

#[allow(warnings)]
pub mod generated;

pub use generated::*;
"""

CARGO_TOML = """\
# Generated by scripts/generate.py from icoschema/schema/linkml/dataset.yaml: do not edit.
[package]
name = "icoschema-gen"
version = "{version}"
edition = "2021"
publish = false

[lib]
name = "icoschema_gen"

[dependencies]
serde = {{ version = "1.0", features = ["derive"], optional = true }}
serde-value = "0.7.0"
serde_yml = {{ version = "0.0.12", optional = true }}
serde_path_to_error = {{ version = "0.1.17", optional = true }}

[features]
default = ["serde"]
serde = ["dep:serde", "dep:serde_yml", "dep:serde_path_to_error"]

# The generated code also has PyO3 / stub-generation variants, which this crate does not build.
[lints.rust]
unexpected_cfgs = {{ level = "allow" }}
"""


def tool(name: str) -> str:
    """A console script of the current environment (`uv run` puts it next to the interpreter)."""
    found = Path(sys.executable).parent / name
    return str(found) if found.exists() else name


def generate_python() -> str:
    result = subprocess.run([tool("gen-python"), str(SCHEMA)], check=True, capture_output=True, text=True)
    return result.stdout


def generate_rust(target: Path) -> None:
    with tempfile.TemporaryDirectory() as tmp:
        raw = Path(tmp) / "raw"
        raw.mkdir()
        subprocess.run(
            [tool("gen-rust"), "-o", str(raw), "-n", "icoschema-gen", "--handwritten-lib", "-s", str(SCHEMA)],
            check=True,
            capture_output=True,
        )
        version = re.search(r'^version = "([^"]+)"', (raw / "Cargo.toml").read_text(), re.MULTILINE)
        if version is None:
            sys.exit("gen-rust wrote no Cargo.toml version")
        for stale in (target / "src/generated").glob("*.rs") if (target / "src/generated").exists() else ():
            stale.unlink()
        (target / "src/generated").mkdir(parents=True, exist_ok=True)
        for name in RUST_FILES:
            shutil.copyfile(raw / "src/generated" / name, target / "src/generated" / name)
        (target / "src/lib.rs").write_text(LIB_RS)
        (target / "Cargo.toml").write_text(CARGO_TOML.format(version=version.group(1)))


def without_date(text: str) -> str:
    return re.sub(r"^# Generation date: .*\n", "", text, flags=re.MULTILINE)


def tree(path: Path) -> dict[str, str]:
    return {str(p.relative_to(path)): p.read_text() for p in sorted(path.rglob("*")) if p.is_file()}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only compare with the committed files")
    check = parser.parse_args().check

    python = generate_python()
    if check:
        stale = []
        if without_date(python) != without_date(PYTHON_OUT.read_text()):
            stale.append(str(PYTHON_OUT.relative_to(ROOT)))
        with tempfile.TemporaryDirectory() as tmp:
            fresh = Path(tmp)
            generate_rust(fresh)
            committed = tree(RUST_OUT)
            committed.pop("target", None)
            if tree(fresh) != {k: v for k, v in committed.items() if not k.startswith("target/")}:
                stale.append(str(RUST_OUT.relative_to(ROOT)))
        if stale:
            sys.exit("generated code is out of date with dataset.yaml (run `just generate`): " + ", ".join(stale))
        print("generated code is up to date")
        return

    if without_date(python) != without_date(PYTHON_OUT.read_text()):  # keep the file (and git) quiet otherwise
        PYTHON_OUT.write_text(python)
    generate_rust(RUST_OUT)
    print(f"wrote {PYTHON_OUT.relative_to(ROOT)} and {RUST_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
