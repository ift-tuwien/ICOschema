"""Regenerate the Python and Rust code from the LinkML schemas.

    uv run python scripts/generate.py            # write icoschema/vN/schema/generated/{dataset.py,rust}
    uv run python scripts/generate.py --check    # fail if the committed files are stale

Every schema version (`icoschema/vN/schema/dataset.yaml`) gets its generated Python dataclasses. The Rust
crate is generated for the versions in `RUST_VERSIONS` only.

The Rust crate is what `gen-rust` writes, minus the parts this repository does not use (the
PyO3 stubs and the `stub_gen` binary), with a fixed `lib.rs` (the generated shim re-exports
`chrono` without depending on it) and a trimmed `Cargo.toml`. Both are reproducible: the same
schema always gives byte-identical Rust files.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# the generators write text in the locale's encoding unless told otherwise (cp1252 on Windows)
ENV = {**os.environ, "PYTHONUTF8": "1", "PYTHONIOENCODING": "utf-8"}
SCHEMA_VERSIONS = sorted(int(p.name[1:]) for p in (ROOT / "icoschema").glob("v[0-9]*") if p.is_dir())
RUST_VERSIONS = (1, 2)
RUST_FILES = ("mod.rs", "poly.rs", "poly_containers.rs", "serde_utils.rs")

LIB_RS = """\
//! Generated from `icoschema/v{version}/schema/dataset.yaml`: run `just generate`, do not edit.
//!
//! Plain data types (no behaviour); the convenience API lives in the `icoschema` crate.

#[allow(warnings)]
pub mod generated;

pub use generated::*;
"""

CARGO_TOML = """\
# Generated by scripts/generate.py from icoschema/v{schema}/schema/dataset.yaml: do not edit.
[package]
name = "icoschema-gen-v{schema}"
version = "{version}"
edition = "2021"
publish = false

[lib]
name = "icoschema_gen_v{schema}"

[dependencies]
serde = {{ version = "1.0", features = ["derive"], optional = true }}
serde-value = "0.7.0"
serde_yml = {{ version = "0.0.12", optional = true }}
serde_path_to_error = {{ version = "0.1.17", optional = true }}

[features]
default = ["serde"]
serde = ["dep:serde", "dep:serde_yml", "dep:serde_path_to_error"]

# The generated code also has PyO3 / stub-generation variants, which this crate does not build.
[lints.rust]
unexpected_cfgs = {{ level = "allow" }}
"""


def schema_of(version: int) -> Path:
    return ROOT / f"icoschema/v{version}/schema/dataset.yaml"


def python_out(version: int) -> Path:
    return ROOT / f"icoschema/v{version}/schema/generated/dataset.py"


def rust_out(version: int) -> Path:
    return ROOT / f"icoschema/v{version}/schema/generated/rust"


def tool(name: str) -> str:
    """A console script of the current environment (`uv run` puts it next to the interpreter)."""
    found = Path(sys.executable).parent / name
    return str(found) if found.exists() else name


def generate_python(version: int) -> str:
    result = subprocess.run(
        [tool("gen-python"), str(schema_of(version))],
        check=True,
        capture_output=True,
        text=True,
        encoding="utf-8",
        env=ENV,
    )
    return result.stdout


def generate_rust(version: int, target: Path) -> None:
    with tempfile.TemporaryDirectory() as tmp:
        raw = Path(tmp) / "raw"
        raw.mkdir()
        # gen-rust cannot handle `designates_type` (it fails building the subtype enum), and the Rust code does not
        # use the designator (the storage code knows the kind of every conversion), so it generates from a copy
        # of the schema without that line.
        schema = Path(tmp) / "dataset.yaml"
        text = schema_of(version).read_text(encoding="utf-8")
        stripped = re.sub(r"^[ \t]*designates_type: true\r?\n", "", text, flags=re.MULTILINE)
        schema.write_text(stripped, encoding="utf-8")
        subprocess.run(
            [
                tool("gen-rust"),
                "-o", str(raw),
                "-n", f"icoschema-gen-v{version}",
                "--handwritten-lib",
                "-s", str(schema),
            ],
            check=True,
            capture_output=True,
            env=ENV,
        )
        found = re.search(r'^version = "([^"]+)"', (raw / "Cargo.toml").read_text(encoding="utf-8"), re.MULTILINE)
        if found is None:
            sys.exit("gen-rust wrote no Cargo.toml version")
        for stale in (target / "src/generated").glob("*.rs") if (target / "src/generated").exists() else ():
            stale.unlink()
        (target / "src/generated").mkdir(parents=True, exist_ok=True)
        for name in RUST_FILES:
            shutil.copyfile(raw / "src/generated" / name, target / "src/generated" / name)
        (target / "src/lib.rs").write_text(LIB_RS.format(version=version), encoding="utf-8", newline="\n")
        (target / "Cargo.toml").write_text(
            CARGO_TOML.format(version=found.group(1), schema=version), encoding="utf-8", newline="\n"
        )


def without_date(text: str) -> str:
    return re.sub(r"^# Generation date: .*\n", "", text, flags=re.MULTILINE)


def tree(path: Path) -> dict[str, str]:
    return {str(p.relative_to(path)): p.read_text(encoding="utf-8") for p in sorted(path.rglob("*")) if p.is_file()}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only compare with the committed files")
    check = parser.parse_args().check

    stale: list[str] = []
    written: list[str] = []
    for version in SCHEMA_VERSIONS:
        python = generate_python(version)
        out = python_out(version)
        python_stale = without_date(python) != without_date(out.read_text(encoding="utf-8"))
        if check:
            if python_stale:
                stale.append(str(out.relative_to(ROOT)))
        elif python_stale:  # keep the file (and git) quiet otherwise
            out.write_text(python, encoding="utf-8", newline="\n")
            written.append(str(out.relative_to(ROOT)))
        if version not in RUST_VERSIONS:
            continue
        rust = rust_out(version)
        if check:
            with tempfile.TemporaryDirectory() as tmp:
                fresh = Path(tmp)
                generate_rust(version, fresh)
                committed = {k: v for k, v in tree(rust).items() if not k.startswith("target")} if rust.exists() else {}
                if tree(fresh) != committed:
                    stale.append(str(rust.relative_to(ROOT)))
        else:
            generate_rust(version, rust)
            written.append(str(rust.relative_to(ROOT)))

    if check:
        if stale:
            sys.exit("generated code is out of date with dataset.yaml (run `just generate`): " + ", ".join(stale))
        print("generated code is up to date")
    else:
        print("wrote " + (", ".join(written) or "nothing (up to date)"))


if __name__ == "__main__":
    main()
